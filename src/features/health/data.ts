// Fixed seed: repeatable fixtures, never regenerated by an LLM or on refresh.
function seededRandom(seed: number) {
  let state = seed;
  return () => {
    state = (Math.imul(1664525, state) + 1013904223) >>> 0;
    return state / 4294967296;
  };
}
