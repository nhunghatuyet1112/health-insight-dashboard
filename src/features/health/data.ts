export function generateRecords(): HealthRecord[] {
  // Reset per call so the exported generator is reproducible too.
  const r = seededRandom(42);
  const weeks = [
    {
      steps: [4500, 5800, 5100, 6200, 4700, 6500, 5000],
      sleep: [5.8, 6.3, 6.1, 6.6, 5.7, 6.8, 6.1],
      active: [10, 15, 10, 20, 0, 25, 12],
    },
    {
      steps: [5300, 6600, 5800, 7100, 5500, 7300, 5800],
      sleep: [6.1, 6.6, 6.4, 6.9, 6, 7.1, 6.4],
      active: [10, 20, 10, 20, 0, 30, 15],
    },
    {
      steps: [5900, 7200, 6400, 7700, 6100, 7900, 6400],
      sleep: [6.3, 6.8, 6.6, 7.1, 6.2, 7.3, 6.6],
      active: [13, 20, 15, 25, 0, 30, 20],
    },
  ];
  return Array.from({ length: 28 }, (_, i) => {
    const week = Math.floor(i / 7),
      day = i % 7;
    const [steps, sleepHours, activeMinutes, waterMl] =
      week === 3
        ? latest[day]
        : [
            weeks[week].steps[day],
            weeks[week].sleep[day],
            weeks[week].active[day],
            Math.round((1500 + week * 130 + r() * 400) / 100) * 100,
          ];
    const date = new Date(Date.UTC(2026, 8, 21 + i)).toISOString().slice(0, 10);
    const bedtimeMinutes = Math.round((6.5 * 60 - sleepHours * 60) / 5) * 5;
    const bedtimeTotal = (24 * 60 + bedtimeMinutes) % (24 * 60);
    return {
      date,
      steps,
      sleepHours,
      activeMinutes,
      waterMl,
      bedtime: `${String(Math.floor(bedtimeTotal / 60)).padStart(2, "0")}:${String(bedtimeTotal % 60).padStart(2, "0")}`,
      wakeTime: "06:30",
      restingHeartRateBpm:
        i === 8 || i === 16 ? null : Math.round(69 - week + r() * 5),
      mood:
        i === 4
          ? null
          : (Math.min(5, Math.max(1, Math.round(sleepHours - 3))) as Score),
      energy:
        i === 11 ? null : sleepHours >= 7.5 ? 4 : sleepHours < 6.3 ? 2 : 3,
      workout:
        activeMinutes >= 30
          ? "Yoga & walking"
          : activeMinutes > 0
            ? "Walking"
            : null,
      source: "synthetic",
    };
  });
}
