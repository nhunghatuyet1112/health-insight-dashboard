import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const spec = JSON.parse(
  await readFile(new URL("src/design-system/tokens.json", root), "utf8"),
);
const aliases = {
  foreground: "text-primary",
  "primary-foreground": "on-primary",
  "secondary-foreground": "on-secondary",
  "accent-foreground": "on-tertiary",
  card: "surface",
  "card-foreground": "text-primary",
  popover: "surface-container",
  "popover-foreground": "text-primary",
  muted: "surface-container-high",
  "muted-foreground": "text-secondary",
  input: "border",
  ring: "primary",
  destructive: "error",
  "destructive-foreground": "on-error",
  "text-muted": "text-secondary",
  "chart-1": "primary",
  "chart-2": "accent",
  "chart-3": "secondary",
  "chart-4": "tertiary-fixed-dim",
  "chart-5": "primary-fixed",
};
const families = {
  Inter: '"Inter Variable", sans-serif',
  "Space Grotesk": '"Space Grotesk Variable", sans-serif',
  "JetBrains Mono": '"JetBrains Mono Variable", monospace',
};
const lines = [
  "/* Generated by npm run design:tokens from tokens.json. Do not edit directly. */",
  ":root {",
];
for (const [key, value] of Object.entries(spec.colors))
  lines.push(`  --ds-color-${key}: ${value};`);
for (const [key, value] of Object.entries(spec.spacing))
  lines.push(`  --ds-spacing-${key}: ${value};`);
for (const [key, value] of Object.entries(spec.rounded))
  lines.push(`  --ds-radius-${key.toLowerCase()}: ${value};`);
for (const [key, t] of Object.entries(spec.typography)) {
  if (!families[t.fontFamily]) throw new Error(`Unknown font: ${t.fontFamily}`);
  lines.push(
    `  --type-${key}: ${t.fontWeight} ${t.fontSize}/${t.lineHeight} ${families[t.fontFamily]};`,
  );
  lines.push(`  --type-${key}-tracking: ${t.letterSpacing ?? "normal"};`);
}
lines.push("}", "@theme inline {");
for (const key of Object.keys(spec.colors))
  lines.push(`  --color-${key}: var(--ds-color-${key});`);
for (const [key, value] of Object.entries(aliases))
  lines.push(`  --color-${key}: var(--ds-color-${value});`);
for (const [key, t] of Object.entries(spec.typography)) {
  lines.push(
    `  --font-${key}: ${families[t.fontFamily]};`,
    `  --text-${key}: ${t.fontSize};`,
    `  --text-${key}--line-height: ${t.lineHeight};`,
    `  --text-${key}--font-weight: ${t.fontWeight};`,
  );
  if (t.letterSpacing)
    lines.push(`  --text-${key}--letter-spacing: ${t.letterSpacing};`);
}
lines.push(
  `  --font-sans: ${families[spec.typography["body-md"].fontFamily]};`,
  `  --font-mono: ${families["JetBrains Mono"]};`,
);
for (const key of Object.keys(spec.spacing))
  lines.push(`  --spacing-${key}: var(--ds-spacing-${key});`);
for (const key of Object.keys(spec.rounded))
  lines.push(
    `  --radius-${key.toLowerCase()}: var(--ds-radius-${key.toLowerCase()});`,
  );
lines.push("}", "");
const output = lines.join("\n");
const target = new URL("src/design-system/theme.css", root);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error(
      "Design tokens are out of sync. Run npm run design:tokens.",
    );
  console.log(`Design tokens verified: ${spec.version}`);
} else {
  await writeFile(target, output);
  console.log(`Generated design tokens: ${spec.version}`);
}
